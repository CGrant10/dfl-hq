import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const sources=JSON.parse(readFileSync(new URL('css/shared-styles.json',root),'utf8'));
const parts=sources.map(path=>{
  if(!/^css\/[a-z0-9-]+\.css$/.test(path))throw Error('Invalid shared stylesheet path');
  const css=readFileSync(new URL(path,root),'utf8');
  if(/@import\b|@charset\b/.test(css))throw Error(`Keep imports/charset outside the shared bundle: ${path}`);
  return `/* Source: ${path} */\n${css}`;
});
writeFileSync(new URL('css/app-shared.css',root),`/* Generated by tools/build-shared-css.mjs. Edit the source sheets. */\n${parts.join('\n\n')}\n`);
console.log(`Shared CSS: ${sources.length} ordered sheets → one request`);

import {build} from 'vite';
import {readdirSync,writeFileSync,readFileSync,rmSync} from 'node:fs';
import {resolve,relative,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const version=JSON.parse(readFileSync(join(root,'package.json'),'utf8')).version;
const output=resolve(root,'js/bundle',version);
await build({configFile:resolve(root,'vite.app.config.js')});
function files(dir){return readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?files(join(dir,e.name)):[join(dir,e.name)]);}
const scripts=files(output).filter(f=>f.endsWith('.js')).map(f=>'./'+relative(root,f).replaceAll('\\','/')).sort();
const bundledStyles=JSON.parse(readFileSync(join(root,'css/shared-styles.json'),'utf8')).map(path=>'./'+path);
writeFileSync(join(output,'precache.js'),`// Generated by tools/build-app.mjs; release URLs are immutable.\nself.DFL_BUNDLE_RELEASE=${JSON.stringify(version)};\nself.DFL_BUNDLE_SHELL=${JSON.stringify(scripts,null,2)};\nself.DFL_BUNDLE_STYLES=${JSON.stringify(bundledStyles)};\n`);
// Keep one previous release for open tabs finishing an update.
const releases=readdirSync(resolve(root,'js/bundle')).filter(v=>/^\d+\.\d+\.\d+$/.test(v)&&v!==version).sort((a,b)=>{const x=a.split('.').map(Number),y=b.split('.').map(Number);return y[0]-x[0]||y[1]-x[1]||y[2]-x[2]});
for(const old of releases.slice(1))rmSync(resolve(root,'js/bundle',old),{recursive:true,force:true});
console.log(`Built ${scripts.length} application modules for ${version}`);
